#!/usr/bin/env python3
"""Fetch a UFO model into the content cache and print the path MG5 should import.

    python scripts/fetch_model.py NAME                 # a model from models.toml
    python scripts/fetch_model.py --list               # what the registry knows
    python scripts/fetch_model.py --git URL --rev SHA [--subdir PATH] --name NAME      # ad hoc, git
    python scripts/fetch_model.py --url URL --sha256 HEX [--subdir PATH] --name NAME   # ad hoc, archive
    ... add  --restriction massless  to check that restriction exists

The last line on stdout is the absolute path of the UFO directory (without any "-restriction"),
so a caller can do:   import model "$(python scripts/fetch_model.py NAME)-massless"
Everything else (progress, warnings) goes to stderr.

Design rules
  * The cache is content-keyed and never edited after it is written:
        <cache>/models/<name>__<tree-hash12>/<ufo-dir>/        the UFO
        <cache>/models/<name>__<tree-hash12>/provenance.json   where it came from
  * A source is pinned: a full 40-hex git commit (not a tag, tags move) or an archive sha256.
  * models.lock records the tree hash of what was fetched. A later fetch that produces a different
    tree is an error, not a silent update. First use of an unlocked model records it (commit the file).
  * UFO models are Python code that MG5 executes. Only fetch sources you trust; the pinning makes
    sure you get the same bytes every time, it does not make them safe.
  * MADLAD_OFFLINE=1 refuses to touch the network (for cluster nodes without internet).
"""
import argparse, fcntl, hashlib, json, os, re, shutil, subprocess, sys, tarfile, tempfile, time
import urllib.request
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # python < 3.11
    sys.exit("fetch_model.py needs Python 3.11+ (tomllib); run it inside 'pixi run'.")

ROOT = Path(__file__).resolve().parent.parent
CACHE = Path(os.environ.get("MADLAD_CACHE", ROOT / "cache")) / "models"
REGISTRY = ROOT / "models.toml"
LOCK = ROOT / "models.lock"
NAME_RE = re.compile(r"^[A-Za-z0-9_.]+$")          # no '-': MG5 reads the last '-' as the restriction
SHA_RE = re.compile(r"^[0-9a-f]{40}$")
REQUIRED = ["__init__.py", "particles.py", "parameters.py", "vertices.py",
            "couplings.py", "lorentz.py", "object_library.py"]
SKIP_PARTS = {"__pycache__"}
SKIP_SUFFIX = {".pyc", ".pkl"}                       # generated by MG5/Python, not part of the model


def log(*a):
    print("[model]", *a, file=sys.stderr)


def die(msg):
    sys.exit("[model:error] " + msg)


def run(cmd, **kw):
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, **kw)
    if r.returncode:
        raise RuntimeError("%s failed (exit %d):\n%s" % (" ".join(map(str, cmd)), r.returncode, r.stdout[-2000:]))
    return r.stdout


def tree_hash(d: Path) -> str:
    """Deterministic hash of a directory: relative path + content of every regular file."""
    h = hashlib.sha256()
    for p in sorted(d.rglob("*")):
        rel = p.relative_to(d)
        if SKIP_PARTS & set(rel.parts) or p.suffix in SKIP_SUFFIX:
            continue
        if p.is_symlink():
            die("%s is a symlink; refusing (a model must not point outside itself)" % rel)
        if p.is_file():
            h.update(rel.as_posix().encode() + b"\0" + hashlib.sha256(p.read_bytes()).digest())
    return h.hexdigest()


def load_registry():
    if not REGISTRY.exists():
        return {}
    return tomllib.loads(REGISTRY.read_text()).get("models", {})


def load_lock():
    return json.loads(LOCK.read_text()) if LOCK.exists() else {}


def save_lock(lock):
    LOCK.write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")


def fetch_git(spec, dest: Path):
    url, rev, sub = spec["git"], spec["rev"], spec.get("subdir", "")
    if not SHA_RE.match(rev):
        die("'rev' must be a full 40-character commit SHA (tags can move), got %r" % rev)
    if not shutil.which("git"):
        raise RuntimeError("git not found")
    run(["git", "init", "-q", str(dest)])
    run(["git", "-C", str(dest), "remote", "add", "origin", url])
    if sub:   # fetch only this folder's blobs
        run(["git", "-C", str(dest), "config", "core.sparseCheckout", "true"])
        (dest / ".git" / "info").mkdir(exist_ok=True)
        (dest / ".git" / "info" / "sparse-checkout").write_text("/" + sub.strip("/") + "/\n")
        run(["git", "-C", str(dest), "config", "remote.origin.promisor", "true"])
        run(["git", "-C", str(dest), "config", "remote.origin.partialclonefilter", "blob:none"])
        fetch = ["git", "-C", str(dest), "fetch", "-q", "--depth", "1", "--filter=blob:none", "origin", rev]
    else:
        fetch = ["git", "-C", str(dest), "fetch", "-q", "--depth", "1", "origin", rev]
    run(fetch)
    run(["git", "-C", str(dest), "checkout", "-q", "FETCH_HEAD"])
    got = run(["git", "-C", str(dest), "rev-parse", "HEAD"]).strip()
    if got != rev:
        die("fetched commit %s, expected %s" % (got, rev))
    return dest / sub if sub else dest


def fetch_archive(spec, dest: Path):
    url, want, sub = spec["url"], spec["sha256"], spec.get("subdir", "")
    dest.mkdir(parents=True)
    arc = dest / "_download"
    h = hashlib.sha256()
    with urllib.request.urlopen(url, timeout=120) as r, open(arc, "wb") as f:
        while True:
            chunk = r.read(1 << 20)
            if not chunk:
                break
            h.update(chunk); f.write(chunk)
    if h.hexdigest() != want.lower():
        die("archive sha256 mismatch for %s\n  expected %s\n  got      %s" % (url, want, h.hexdigest()))
    out = dest / "_extract"
    out.mkdir()
    with tarfile.open(arc) as t:
        for m in t.getmembers():                     # no absolute paths, no '..', no links
            if m.issym() or m.islnk() or m.name.startswith("/") or ".." in Path(m.name).parts:
                die("unsafe member in archive: %s" % m.name)
        t.extractall(out)
    arc.unlink()
    top = [p for p in out.iterdir()]
    base = top[0] if len(top) == 1 and top[0].is_dir() else out   # GitHub tarballs wrap one folder
    return base / sub if sub else base


def validate_ufo(d: Path):
    missing = [f for f in REQUIRED if not (d / f).is_file()]
    if missing:
        die("%s is not a UFO model: missing %s" % (d, ", ".join(missing)))
    return sorted(p.name[len("restrict_"):-len(".dat")] for p in d.glob("restrict_*.dat"))


def install(name, spec, restriction=None, offline=False):
    if not NAME_RE.match(name):
        die("model name %r: only letters, digits, '_' and '.' (a '-' would be read by MG5 as a restriction)" % name)
    lock = load_lock()
    known = lock.get(name, {}).get("tree_sha256")
    ufo_name = Path(spec.get("subdir") or name).name

    # already cached under the locked hash? then no network and nothing to do.
    if known:
        d = CACHE / ("%s__%s" % (name, known[:12])) / ufo_name
        if d.is_dir():
            return finish(d, validate_ufo(d), restriction, "cached")
    if offline:
        die("MADLAD_OFFLINE is set and %s is not in the cache (%s). Fetch it on a machine with network "
            "access, or copy its folder into %s." % (name, "no lock entry" if not known else known[:12], CACHE))

    CACHE.mkdir(parents=True, exist_ok=True)
    with open(CACHE / ".lock", "w") as lk:                # one fetch at a time, e.g. parallel jobs
        fcntl.flock(lk, fcntl.LOCK_EX)
        tmp = Path(tempfile.mkdtemp(prefix=".tmp-", dir=CACHE))
        try:
            log("fetching %s from %s" % (name, spec.get("git") or spec.get("url")))
            src = fetch_git(spec, tmp / "w") if "git" in spec else fetch_archive(spec, tmp / "w")
            if not src.is_dir():
                die("subdir %r not found in the source" % spec.get("subdir"))
            restrictions = validate_ufo(src)
            th = tree_hash(src)
            if known and known != th:
                die("tree hash for %s changed!\n  locked: %s\n  now:    %s\n"
                    "The source no longer matches what was recorded in models.lock." % (name, known, th))
            final_parent = CACHE / ("%s__%s" % (name, th[:12]))
            final = final_parent / ufo_name
            if not final.is_dir():
                final_parent.mkdir()
                shutil.copytree(src, final, ignore=shutil.ignore_patterns(".git"))
                (final_parent / "provenance.json").write_text(json.dumps({
                    "name": name, "source": {k: spec[k] for k in ("git", "rev", "url", "sha256", "subdir") if k in spec},
                    "tree_sha256": th, "restrictions": restrictions,
                    "fetched_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}, indent=2) + "\n")
            if not known:
                lock[name] = {"tree_sha256": th, "source": {k: spec[k] for k in ("git", "rev", "url", "sha256", "subdir") if k in spec}}
                save_lock(lock)
                log("recorded %s in models.lock (commit this file)" % name)
            return finish(final, restrictions, restriction, "fetched")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


def finish(d, restrictions, restriction, how):
    log("%s: %s" % (how, d))
    log("restrictions available: %s" % (", ".join(restrictions) or "(none)"))
    if restriction and restriction not in restrictions:
        die("restriction %r not in this model; available: %s" % (restriction, ", ".join(restrictions)))
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--git"); ap.add_argument("--rev")
    ap.add_argument("--url"); ap.add_argument("--sha256")
    ap.add_argument("--subdir", default="")
    ap.add_argument("--restriction")
    ap.add_argument("--name", dest="name_opt")
    a = ap.parse_args()
    reg = load_registry()
    if a.list:
        for n, s in sorted(reg.items()):
            print("%-40s %s @ %s" % (n, s.get("git") or s.get("url"), (s.get("rev") or s.get("sha256") or "")[:10]))
        return
    name = a.name_opt or a.name
    if not name:
        ap.error("give a model NAME from models.toml, or --name with --git/--url")
    if a.git or a.url:
        spec = {"subdir": a.subdir}
        if a.git:
            if not a.rev: ap.error("--git needs --rev (a full commit SHA)")
            spec.update(git=a.git, rev=a.rev)
        else:
            if not a.sha256: ap.error("--url needs --sha256")
            spec.update(url=a.url, sha256=a.sha256)
        spec = {k: v for k, v in spec.items() if v}
    elif name in reg:
        spec = reg[name]
    else:
        die("unknown model %r. Known: %s. For another source use --git/--url." % (name, ", ".join(sorted(reg)) or "(none)"))
    d = install(name, spec, a.restriction, offline=os.environ.get("MADLAD_OFFLINE") == "1")
    print(d)


if __name__ == "__main__":
    main()
