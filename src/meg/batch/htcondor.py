"""HTCondor backend: write the submit description, submit it, ask the queue what is happening.

One submit description with `queue seed,tag from seeds.txt` makes one cluster of N jobs. Every job
runs job.sh in its own scratch directory, with the three small input files transferred in and the
`outbox/` directory transferred out into replicas/<tag>/ whatever the exit status."""
from __future__ import annotations

import json
import re
import shutil
import subprocess
from dataclasses import dataclass, field

from ..util import MegError
from .campaign import Campaign

STATES = {1: "idle", 2: "running", 3: "removed", 4: "completed", 5: "held", 6: "transferring", 7: "suspended"}

JOB_SH = """\
#!/bin/bash
# One MEG replica on a worker node. Arguments: SEED
set -u
mkdir -p outbox
echo "meg job: host $(hostname), seed $1, started $(date -u +%FT%TZ)"
source ./env.sh || { echo "meg job: cannot load env.sh: is the MEG repository visible from this node?" >&2; exit 90; }
# the prebuilt MG5 process: given by path as $2, or transferred in as process.tar.gz
pre="${2:-}"
if [ -z "$pre" ] && [ -f process.tar.gz ]; then pre=process.tar.gz; fi
if [ -n "$pre" ]; then
  exec meg _job --meta campaign.json --config config.json --seed "$1" --outbox outbox --prebuilt "$pre"
fi
exec meg _job --meta campaign.json --config config.json --seed "$1" --outbox outbox
"""

PREPARE_SH = """\
#!/bin/bash
# Build the campaign's MG5 process once and pack it (process.tar.gz in outbox/).
set -u
mkdir -p outbox
echo "meg prepare: host $(hostname), started $(date -u +%FT%TZ)"
source ./env.sh || { echo "meg prepare: cannot load env.sh; is the MEG repo visible from this node?" >&2; exit 90; }
exec meg _prepare --meta campaign.json --config config.json --outbox outbox
"""


def render_submit(c: Campaign, seeds_file: str = "seeds.txt") -> str:
    cfg = c.config()
    ex, hc = cfg.execution, cfg.execution.htcondor
    d = c.dir
    inputs = [d / "campaign.json", d / "config.json", d / "env.sh"]
    arguments = "$(seed)"
    if c.meta.get("build_once"):
        archive = d / "prepare" / "outbox" / "process.tar.gz"
        if ex.process_transfer:
            inputs.append(archive)                       # HTCondor ships it to every job
        else:
            arguments = f"$(seed) {archive}"             # jobs read it in place
    lines = [
        f"# MEG campaign {c.id}. Generated by `meg submit`; resubmit by hand with: condor_submit submit.sub",
        f"universe = {hc.universe}",
        f"executable = {d / 'job.sh'}",
        f"arguments = {arguments}",
        f"batch_name = {c.id}",
        "should_transfer_files = YES",
        "when_to_transfer_output = ON_EXIT",
        "transfer_input_files = " + ", ".join(str(x) for x in inputs),
        "transfer_output_files = outbox",
        "initialdir = replicas/$(tag)",
        "output = job.out",
        "error = job.err",
        f"log = {d / 'condor.log'}",
        f"request_cpus = {max(ex.cores, 1)}",
        f"request_memory = {ex.memory}",
        f"request_disk = {ex.disk}",
        "notification = never",
    ]
    secs = ex.walltime_seconds()
    if secs is not None:
        lines.append(f"+MaxRuntime = {secs}")
    if ex.max_running:
        lines.append(f"max_materialize = {ex.max_running}")
    if hc.requirements:
        lines.append(f"requirements = {hc.requirements}")
    if hc.accounting_group:
        lines.append(f"accounting_group = {hc.accounting_group}")
    lines += list(hc.extra)
    lines.append(f"queue seed,tag from {seeds_file}")
    return "\n".join(lines) + "\n"


def render_prepare(c: Campaign) -> str:
    ex, hc = c.config().execution, c.config().execution.htcondor
    d = c.dir
    lines = [
        f"# MEG campaign {c.id}: build the MG5 process once",
        f"universe = {hc.universe}",
        f"executable = {d / 'prepare.sh'}",
        f"batch_name = {c.id}",
        "should_transfer_files = YES",
        "when_to_transfer_output = ON_EXIT",
        f"transfer_input_files = {d / 'campaign.json'}, {d / 'config.json'}, {d / 'env.sh'}",
        "transfer_output_files = outbox",
        f"initialdir = {d / 'prepare'}",
        "output = job.out",
        "error = job.err",
        f"log = {d / 'condor.log'}",
        f"request_cpus = {max(ex.cores, 1)}",
        f"request_memory = {ex.memory}",
        f"request_disk = {ex.disk}",
        "notification = never",
    ]
    secs = ex.walltime_seconds()
    if secs is not None:
        lines.append(f"+MaxRuntime = {secs}")
    if hc.requirements:
        lines.append(f"requirements = {hc.requirements}")
    if hc.accounting_group:
        lines.append(f"accounting_group = {hc.accounting_group}")
    lines += list(hc.extra)
    lines.append("queue")
    return "\n".join(lines) + "\n"


def render_dag(submit_file: str = "submit.sub") -> str:
    return ("# PREPARE builds the MG5 process once; REPLICAS (one job per seed) start when it has succeeded\n"
            "JOB PREPARE prepare.sub\n"
            f"JOB REPLICAS {submit_file}\n"
            "PARENT PREPARE CHILD REPLICAS\n")


def write_files(c: Campaign) -> None:
    (c.dir / "job.sh").write_text(JOB_SH)
    (c.dir / "job.sh").chmod(0o755)
    (c.dir / "submit.sub").write_text(render_submit(c))
    if c.meta.get("build_once"):
        (c.dir / "prepare.sh").write_text(PREPARE_SH)
        (c.dir / "prepare.sh").chmod(0o755)
        (c.dir / "prepare.sub").write_text(render_prepare(c))
        (c.dir / "campaign.dag").write_text(render_dag())


def _need(tool: str) -> str:
    path = shutil.which(tool)
    if not path:
        raise MegError(f"{tool} not found: run this on an HTCondor submit host "
                       "(or use --dry-run to only write the files)")
    return path


def submit(c: Campaign, submit_file: str = "submit.sub") -> int:
    r = subprocess.run([_need("condor_submit"), submit_file], cwd=c.dir, capture_output=True, text=True)
    if r.returncode != 0:
        raise MegError(f"condor_submit failed:\n{r.stdout}{r.stderr}")
    m = re.search(r"submitted to cluster (\d+)", r.stdout)
    if not m:
        raise MegError(f"could not find the cluster id in condor_submit's output:\n{r.stdout}")
    return int(m.group(1))


@dataclass
class QueueInfo:
    seeds: dict[int, tuple[str, str]] = field(default_factory=dict)     # seed -> (state, hold reason)
    prepare: tuple[str, str] | None = None                              # the PREPARE job, if it is queued
    dag_alive: bool = False                                             # DAGMan itself is still running


def _rows(tool: str, args: list[str]) -> list[dict] | None:
    r = subprocess.run([tool, *args, "-json", "-attributes", "ProcId,JobStatus,HoldReason,Args,Arguments"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        return None
    return json.loads(r.stdout) if r.stdout.strip() else []


def queue_states(c: Campaign) -> QueueInfo | None:
    """What the queue says about this campaign's jobs; None if the queue cannot be asked."""
    tool = shutil.which("condor_q")
    if not tool:
        return None
    info = QueueInfo()
    for sub in c.meta.get("submissions", []):
        if sub.get("dag_cluster") is not None:
            dag = sub["dag_cluster"]
            alive = _rows(tool, [str(dag)])
            nodes = _rows(tool, ["-constraint", f"DAGManJobId == {dag}"])
            if alive is None or nodes is None:
                return None
            info.dag_alive = info.dag_alive or bool(alive)
            for row in nodes:
                arg = str(row.get("Args") or row.get("Arguments") or "").split()
                state = (STATES.get(int(row.get("JobStatus", 0)), "unknown"), str(row.get("HoldReason", "")))
                if arg and arg[0].isdigit():
                    info.seeds[int(arg[0])] = state
                else:
                    info.prepare = state
            continue
        cluster = sub.get("cluster")
        if cluster is None:
            continue
        rows = _rows(tool, [str(cluster)])
        if rows is None:
            return None
        seeds = sub["seeds"]
        for row in rows:
            proc = int(row.get("ProcId", -1))
            if 0 <= proc < len(seeds):
                info.seeds[seeds[proc]] = (STATES.get(int(row.get("JobStatus", 0)), "unknown"),
                                           str(row.get("HoldReason", "")))
    return info


def submit_dag(c: Campaign, dag_file: str = "campaign.dag") -> int:
    r = subprocess.run([_need("condor_submit_dag"), "-f", dag_file], cwd=c.dir, capture_output=True, text=True)
    if r.returncode != 0:
        raise MegError(f"condor_submit_dag failed:\n{r.stdout}{r.stderr}")
    m = re.search(r"submitted to cluster (\d+)", r.stdout)
    if not m:
        raise MegError(f"could not find the cluster id in condor_submit_dag's output:\n{r.stdout}")
    return int(m.group(1))


def remove(c: Campaign) -> list[int]:
    tool = _need("condor_rm")
    done = []
    for sub in c.meta.get("submissions", []):
        cluster = sub.get("dag_cluster") if sub.get("dag_cluster") is not None else sub.get("cluster")
        if cluster is not None:
            subprocess.run([tool, str(cluster)], capture_output=True, text=True)
            done.append(cluster)
    return done
