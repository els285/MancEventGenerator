"""HTCondor backend: write the submit description, submit it, ask the queue what is happening.

One submit description with `queue seed,tag from seeds.txt` makes one cluster of N jobs. Every job
runs job.sh in its own scratch directory, with the three small input files transferred in and the
`outbox/` directory transferred out into replicas/<tag>/ whatever the exit status."""
from __future__ import annotations

import json
import re
import shutil
import subprocess

from ..util import MegError
from .campaign import Campaign

STATES = {1: "idle", 2: "running", 3: "removed", 4: "completed", 5: "held", 6: "transferring", 7: "suspended"}

JOB_SH = """\
#!/bin/bash
# One MEG replica on a worker node. Arguments: SEED
set -u
mkdir -p outbox
echo "meg job: host $(hostname), seed $1, started $(date -u +%FT%TZ)"
source ./env.sh || { echo "meg job: cannot load env.sh: is the MEG repository visible from this node?" >&2; exit 90; }
exec meg _job --meta campaign.json --config config.json --seed "$1" --outbox outbox
"""


def render_submit(c: Campaign, seeds_file: str = "seeds.txt") -> str:
    cfg = c.config()
    ex, hc = cfg.execution, cfg.execution.htcondor
    d = c.dir
    lines = [
        f"# MEG campaign {c.id}. Generated by `meg submit`; resubmit by hand with: condor_submit submit.sub",
        f"universe = {hc.universe}",
        f"executable = {d / 'job.sh'}",
        "arguments = $(seed)",
        f"batch_name = {c.id}",
        "should_transfer_files = YES",
        "when_to_transfer_output = ON_EXIT",
        f"transfer_input_files = {d / 'campaign.json'}, {d / 'config.json'}, {d / 'env.sh'}",
        "transfer_output_files = outbox",
        "initialdir = replicas/$(tag)",
        "output = job.out",
        "error = job.err",
        f"log = {d / 'condor.log'}",
        f"request_cpus = {max(ex.cores, 1)}",
        f"request_memory = {ex.memory}",
        f"request_disk = {ex.disk}",
        "notification = never",
    ]
    secs = ex.walltime_seconds()
    if secs is not None:
        lines.append(f"+MaxRuntime = {secs}")
    if ex.max_running:
        lines.append(f"max_materialize = {ex.max_running}")
    if hc.requirements:
        lines.append(f"requirements = {hc.requirements}")
    if hc.accounting_group:
        lines.append(f"accounting_group = {hc.accounting_group}")
    lines += list(hc.extra)
    lines.append(f"queue seed,tag from {seeds_file}")
    return "\n".join(lines) + "\n"


def write_files(c: Campaign) -> None:
    (c.dir / "job.sh").write_text(JOB_SH)
    (c.dir / "job.sh").chmod(0o755)
    (c.dir / "submit.sub").write_text(render_submit(c))


def _need(tool: str) -> str:
    path = shutil.which(tool)
    if not path:
        raise MegError(f"{tool} not found: run this on an HTCondor submit host "
                       "(or use --dry-run to only write the files)")
    return path


def submit(c: Campaign, submit_file: str = "submit.sub") -> int:
    r = subprocess.run([_need("condor_submit"), submit_file], cwd=c.dir, capture_output=True, text=True)
    if r.returncode != 0:
        raise MegError(f"condor_submit failed:\n{r.stdout}{r.stderr}")
    m = re.search(r"submitted to cluster (\d+)", r.stdout)
    if not m:
        raise MegError(f"could not find the cluster id in condor_submit's output:\n{r.stdout}")
    return int(m.group(1))


def queue_states(c: Campaign) -> dict[int, tuple[str, str]] | None:
    """seed -> (state, hold reason) for jobs still known to the queue; None if the queue can't be asked."""
    tool = shutil.which("condor_q")
    if not tool:
        return None
    out: dict[int, tuple[str, str]] = {}
    for sub in c.meta.get("submissions", []):
        cluster = sub.get("cluster")
        if cluster is None:
            continue
        r = subprocess.run([tool, str(cluster), "-json", "-attributes", "ProcId,JobStatus,HoldReason"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            return None
        rows = json.loads(r.stdout) if r.stdout.strip() else []
        seeds = sub["seeds"]
        for row in rows:
            proc = int(row.get("ProcId", -1))
            if 0 <= proc < len(seeds):
                out[seeds[proc]] = (STATES.get(int(row.get("JobStatus", 0)), "unknown"),
                                    str(row.get("HoldReason", "")))
    return out


def remove(c: Campaign) -> list[int]:
    tool = _need("condor_rm")
    done = []
    for sub in c.meta.get("submissions", []):
        if sub.get("cluster") is not None:
            subprocess.run([tool, str(sub["cluster"])], capture_output=True, text=True)
            done.append(sub["cluster"])
    return done
