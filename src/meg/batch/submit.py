def _env_script(offline: bool) -> str:
    """Shell code that makes `meg` and the whole toolchain available, the way `pixi run` would."""
    root, name = os.environ.get("PIXI_PROJECT_ROOT"), os.environ.get("PIXI_ENVIRONMENT_NAME")
    body = None
    if root and shutil.which("pixi"):
        cmd = ["pixi", "shell-hook", "--manifest-path", str(Path(root) / "pixi.toml"), "--shell", "bash"]
        if name and name != "default":
            cmd += ["-e", name]
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip():
            body = r.stdout
        else:
            log.warning("`pixi shell-hook` failed (%s); falling back to a plain PATH setup",
                        (r.stderr.strip().splitlines() or ["no output"])[-1])
    if body is None:
        prefix = os.environ.get("CONDA_PREFIX")
        if not prefix:
            raise MegError("run `meg submit` inside the MEG environment (`pixi run meg submit ...`) so the "
                           "jobs know which environment to use")
        body = f'export CONDA_PREFIX="{prefix}"\nexport PATH="{prefix}/bin:$PATH"\n'
    extra = [f'export MEG_CACHE="{cache_root()}"']
    if offline:
        extra.append("export MEG_OFFLINE=1")
    head = "# generated by `meg submit`: puts the MEG environment on this node\n"
    return head + body + "\n" + "\n".join(extra) + "\n"


def _frozen(cfg: Config) -> Config:
    """The config the jobs will read: paths made absolute (the job runs elsewhere), cores made concrete."""
    d = cfg.model_dump(mode="json")
    if cfg.detector.kind == "delphes":
        d["detector"]["card"] = str(delphes.resolve_card(cfg.detector.card))
    ex = d["execution"]
    if ex["executor"] == "local":
        conc = ex["max_running"] or 1
        ex["cores"] = ex["cores"] or max(1, sysenv.default_cores() // conc)
    else:
        ex["cores"] = max(ex["cores"], 1)
    return Config.model_validate(d)


def submit(cfg: Config, *, dry_run: bool = False) -> Campaign:
    ex = cfg.execution
    cid = campaign_id(cfg)
    cdir = (ex.campaign_dir / cid).resolve()
    if cdir.exists():
        raise MegError(f"{cdir} already exists. `meg status {cdir}` shows where it stands; use `meg resubmit` "
                       "for failures, or change run.name to start a different campaign.")
    frozen = _frozen(cfg)
    if not dry_run:
        log.info("preparing the toolchain and inputs once, here, so the jobs can run offline ...")
        runner.prepare(frozen)
    seeds = cfg.seeds()
    batch = ex.executor != "local"
    cdir.mkdir(parents=True)
    (cdir / "replicas").mkdir()
    if frozen.execution.build_once:
        (cdir / "prepare").mkdir()
    for s in seeds:
        (cdir / "replicas" / tag(s)).mkdir()
    (cdir / "config.json").write_text(frozen.model_dump_json(indent=2) + "\n")
    (cdir / "seeds.txt").write_text("".join(f"{s},{tag(s)}\n" for s in seeds))
    c = Campaign(cdir, {
        "id": cid, "name": cfg.run.name, "created": datetime.now(UTC).isoformat(timespec="seconds"),
        "meg_version": __version__, "executor": ex.executor, "seeds": seeds, "retrieve": frozen.execution.retrieve,
        "offline": batch, "build_once": frozen.execution.build_once,
        "lockfile_sha256": lockfile_hash(dict(os.environ)), "submissions": [],
    })
    c.save()
    if batch:
        (cdir / "env.sh").write_text(_env_script(offline=True))
        htcondor.write_files(c)
    log.info("campaign %s: %d replicas, seeds %d..%d, retrieving %s", cid, len(seeds), seeds[0], seeds[-1],
             frozen.execution.retrieve)
    log.info("campaign directory: %s", cdir)
    if dry_run:
        what = "condor_submit_dag campaign.dag" if frozen.execution.build_once else "condor_submit submit.sub"
        hint = f" (submit with: cd {cdir} && {what})" if batch else ""
        log.info("dry run: files written, nothing submitted%s", hint)
        return c
    now = datetime.now(UTC).isoformat(timespec="seconds")
    if ex.executor == "htcondor":
        if frozen.execution.build_once:
            dag = htcondor.submit_dag(c)
            c.meta["submissions"].append({"cluster": None, "dag_cluster": dag, "seeds": seeds, "utc": now})
            log.info("submitted a DAG (cluster %d): the process is built once, then %d replica jobs run. "
                     "Follow with: meg status %s", dag, len(seeds), cdir)
        else:
            cluster = htcondor.submit(c)
            c.meta["submissions"].append({"cluster": cluster, "seeds": seeds, "utc": now})
            log.info("submitted %d jobs to HTCondor cluster %d. Follow with: meg status %s",
                     len(seeds), cluster, cdir)
        c.save()
    else:
        c.meta["submissions"].append({"cluster": None, "seeds": seeds, "utc": now})
        c.save()
        prebuilt = _prepare_locally(c) if frozen.execution.build_once else None
        local.run_all(c, seeds, ex.max_running or 1, prebuilt)
    return c


def prepare_archive(c: Campaign) -> Path:
    return c.dir / "prepare" / "outbox" / "process.tar.gz"


def _prepare_locally(c: Campaign) -> Path:
    rc = local.run_prepare(c)
    st = prepare_status(c)
    if rc != 0 or not st or st[0] != "ok":
        raise MegError(f"building the MG5 process failed ({st[1] if st else 'no status'}). "
                       f"See {c.dir / 'prepare' / 'job.out'} and the logs in {c.dir / 'prepare' / 'outbox'}")
    return prepare_archive(c)


def prepare_status(c: Campaign) -> tuple[str, str] | None:
    """('ok' | 'failed', error) once the build-once job has finished; None before that."""
    p = c.dir / "prepare" / "outbox" / "status.json"
    if not p.is_file():
        return None
    try:
        st = json.loads(p.read_text())
    except json.JSONDecodeError:
        return None
    return st["state"], st.get("error", "")


