"""UFO models as pinned, content-keyed inputs.

A model is fetched from a pinned source into an immutable cache directory
    <cache>/models/<name>__<tree-hash12>/<ufo-dir>/
and its content hash is recorded in ./models.lock. A later fetch that yields different bytes is an
error. UFO models are Python code that MG5 executes: pinning guarantees you get the same bytes
every time, it does not make them safe. Only use sources you trust.

Sources: the registry shipped with MEG (data/models.toml), plus an optional ./models.toml of your
own (same format, overrides on name clashes), plus an inline git/url in the run config.
"""
from __future__ import annotations

import fcntl
import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
import tomllib
import urllib.request
from dataclasses import dataclass, field
from importlib import resources
from pathlib import Path

from .cache import cache_dir, offline
from .util import MegError, log, safe_extract

NAME_RE = re.compile(r"^[A-Za-z0-9_.]+$")      # no '-': MG5 reads the last '-' as the restriction
SHA_RE = re.compile(r"^[0-9a-f]{40}$")
REQUIRED = ["__init__.py", "particles.py", "parameters.py", "vertices.py",
            "couplings.py", "lorentz.py", "object_library.py"]
SKIP_PARTS = {"__pycache__"}
SKIP_SUFFIX = {".pyc", ".pkl"}                  # generated by Python/MG5, not part of the model
SOURCE_KEYS = ("git", "rev", "url", "sha256", "subdir")


@dataclass
class FetchedModel:
    name: str
    path: Path                                   # the UFO directory
    tree_sha256: str
    restrictions: list[str] = field(default_factory=list)
    source: dict = field(default_factory=dict)


def lock_path() -> Path:
    return Path(os.environ.get("MEG_MODELS_LOCK", "models.lock")).resolve()


def registry() -> dict[str, dict]:
    reg = tomllib.loads((resources.files("meg") / "data" / "models.toml").read_text())
    models = dict(reg.get("models", {}))
    local = Path("models.toml")
    if local.is_file():
        models.update(tomllib.loads(local.read_text()).get("models", {}))
    return models


def _run(cmd: list[str]) -> str:
    r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    if r.returncode:
        raise MegError(f"{' '.join(cmd)} failed (exit {r.returncode}):\n{r.stdout[-2000:]}")
    return r.stdout


def tree_hash(d: Path) -> str:
    """Deterministic hash of a directory: relative path + content of every regular file."""
    h = hashlib.sha256()
    for p in sorted(d.rglob("*")):
        rel = p.relative_to(d)
        if SKIP_PARTS & set(rel.parts) or p.suffix in SKIP_SUFFIX:
            continue
        if p.is_symlink():
            raise MegError(f"{rel} is a symlink; refusing (a model must not point outside itself)")
        if p.is_file():
            h.update(rel.as_posix().encode() + b"\0" + hashlib.sha256(p.read_bytes()).digest())
    return h.hexdigest()


def _fetch_git(spec: dict, dest: Path) -> Path:
    url, rev, sub = spec["git"], spec["rev"], spec.get("subdir", "")
    if not SHA_RE.match(rev):
        raise MegError(f"'rev' must be a full 40-character commit SHA (tags can move), got {rev!r}")
    if not shutil.which("git"):
        raise MegError("git not found (it is part of the MEG environment; use `pixi run`)")
    _run(["git", "init", "-q", str(dest)])
    _run(["git", "-C", str(dest), "remote", "add", "origin", url])
    fetch = ["git", "-C", str(dest), "fetch", "-q", "--depth", "1", "origin", rev]
    if sub:      # fetch only this folder's blobs
        _run(["git", "-C", str(dest), "config", "core.sparseCheckout", "true"])
        (dest / ".git" / "info").mkdir(exist_ok=True)
        (dest / ".git" / "info" / "sparse-checkout").write_text("/" + sub.strip("/") + "/\n")
        _run(["git", "-C", str(dest), "config", "remote.origin.promisor", "true"])
        _run(["git", "-C", str(dest), "config", "remote.origin.partialclonefilter", "blob:none"])
        fetch.insert(-2, "--filter=blob:none")
    _run(fetch)
    _run(["git", "-C", str(dest), "checkout", "-q", "FETCH_HEAD"])
    got = _run(["git", "-C", str(dest), "rev-parse", "HEAD"]).strip()
    if got != rev:
        raise MegError(f"fetched commit {got}, expected {rev}")
    return dest / sub if sub else dest


def _fetch_archive(spec: dict, dest: Path) -> Path:
    url, want, sub = spec["url"], spec["sha256"], spec.get("subdir", "")
    dest.mkdir(parents=True)
    arc = dest / "_download"
    h = hashlib.sha256()
    with urllib.request.urlopen(url, timeout=120) as r, open(arc, "wb") as f:
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
            f.write(chunk)
    if h.hexdigest() != want.lower():
        raise MegError(f"archive sha256 mismatch for {url}\n  expected {want}\n  got      {h.hexdigest()}")
    out = dest / "_extract"
    safe_extract(arc, out)
    arc.unlink()
    top = list(out.iterdir())
    base = top[0] if len(top) == 1 and top[0].is_dir() else out    # GitHub tarballs wrap one folder
    return base / sub if sub else base


def validate_ufo(d: Path) -> list[str]:
    missing = [f for f in REQUIRED if not (d / f).is_file()]
    if missing:
        raise MegError(f"{d} is not a UFO model: missing {', '.join(missing)}")
    return sorted(p.name[len("restrict_"):-len(".dat")] for p in d.glob("restrict_*.dat"))


def _load_lock() -> dict:
    p = lock_path()
    return json.loads(p.read_text()) if p.exists() else {}


def _save_lock(lock: dict) -> None:
    lock_path().write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")


def _check_restriction(m: FetchedModel, restriction: str | None) -> FetchedModel:
    if restriction and restriction not in m.restrictions:
        raise MegError(f"restriction {restriction!r} not in model {m.name}; "
                       f"available: {', '.join(m.restrictions) or '(none)'}")
    return m


def fetch(name: str, spec: dict | None = None, restriction: str | None = None) -> FetchedModel:
    """Make sure model `name` is in the cache and return it. `spec` overrides the registry."""
    if not NAME_RE.match(name):
        raise MegError(f"model name {name!r}: only letters, digits, '_' and '.' are allowed "
                       "(a '-' would be read by MG5 as a restriction)")
    if spec is None:
        reg = registry()
        if name not in reg:
            raise MegError(f"unknown model {name!r}. Registered: {', '.join(sorted(reg)) or '(none)'}."
                           " Give a git/rev or url/sha256 in the config for another source.")
        spec = reg[name]
    spec = {k: spec[k] for k in SOURCE_KEYS if spec.get(k)}
    if "git" not in spec and "url" not in spec:
        raise MegError(f"model {name}: the source needs 'git' (+rev) or 'url' (+sha256)")
    cache = cache_dir("models")
    lock = _load_lock()
    known = lock.get(name, {}).get("tree_sha256")
    ufo_name = Path(spec.get("subdir") or name).name

    if known:           # already cached under the locked hash: no network, nothing to do
        d = cache / f"{name}__{known[:12]}" / ufo_name
        if d.is_dir():
            return _check_restriction(FetchedModel(name, d, known, validate_ufo(d), spec), restriction)
    if offline():
        raise MegError(f"MEG_OFFLINE=1 and model {name} is not cached "
                       f"({'no lock entry' if not known else known[:12]}). Fetch it on a machine "
                       f"with network access, or copy its folder into {cache}.")

    with open(cache / ".lock", "w") as lk:           # one fetch at a time (parallel jobs)
        fcntl.flock(lk, fcntl.LOCK_EX)
        tmp = Path(tempfile.mkdtemp(prefix=".tmp_", dir=cache))
        try:
            log.info("fetching model %s from %s", name, spec.get("git") or spec.get("url"))
            src = _fetch_git(spec, tmp / "w") if "git" in spec else _fetch_archive(spec, tmp / "w")
            if not src.is_dir():
                raise MegError(f"subdir {spec.get('subdir')!r} not found in the source")
            restrictions = validate_ufo(src)
            th = tree_hash(src)
            if known and known != th:
                raise MegError(f"tree hash for {name} changed!\n  locked: {known}\n  now:    {th}\n"
                               f"The source no longer matches what {lock_path().name} recorded.")
            parent = cache / f"{name}__{th[:12]}"
            final = parent / ufo_name
            if not final.is_dir():
                parent.mkdir(exist_ok=True)
                shutil.copytree(src, final, ignore=shutil.ignore_patterns(".git"))
                (parent / "provenance.json").write_text(json.dumps({
                    "name": name, "source": spec, "tree_sha256": th, "restrictions": restrictions,
                    "fetched_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}, indent=2) + "\n")
            if not known:
                lock[name] = {"tree_sha256": th, "source": spec}
                _save_lock(lock)
                log.info("recorded %s in %s (commit this file)", name, lock_path())
            return _check_restriction(FetchedModel(name, final, th, restrictions, spec), restriction)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
